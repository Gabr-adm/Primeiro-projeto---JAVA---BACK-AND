package testing;

public class Carro {

    String marca;
    String cor;
    String modelo;
    int ano;
    double valor;
    int quantidade;

    Carro(){
    }

    Carro(String marca, String cor, String modelo, int ano, double valor, int quantidade){
        this.marca = marca;
        this.cor = cor;
        this.modelo = modelo;
        this.ano = ano;
        this.valor = valor;
        this.quantidade = quantidade;
    }

}
