package Roadpmap.ExerciciosNv2.Exe3;

public class NumeroComplexo {

    private int numeroReal;
    private int numeroImaginario;

    public NumeroComplexo(int numeroReal, int numeroImaginario) {
        this.numeroReal = numeroReal;
        this.numeroImaginario = numeroImaginario;
    }

    public int getNumeroReal() {
        return numeroReal;
    }

    public void setNumeroReal(int numeroReal) {
        this.numeroReal = numeroReal;
    }

    public int getNumeroImaginario() {
        return numeroImaginario;
    }

    public void setNumeroImaginario(int numeroImaginario) {
        this.numeroImaginario = numeroImaginario;
    }


}
